import assert from 'node:assert/strict';
import {db,ids,as,scalar} from './helpers/lesson-note-test-db.mjs';
await as('teacher');
assert.equal(await scalar("select review_valid_features('{\"show_music\":false}')"),true);
assert.equal(await scalar("select review_valid_features('{\"show_music\":\"false\"}')"),false);
assert.equal(await scalar("select review_valid_features('{\"unknown\":true}')"),false);
await db.exec(`select review_save_experience((select to_jsonb(c)||jsonb_build_object('features',c.features||'{"show_music":false}'::jsonb) from review_site_experience c where id),array[]::uuid[])`);
await as('student');
assert.equal(await scalar("select review_my_hub_settings()->>'show_music'"),'false','Inherited global OFF');
await as('otherTeacher');
await assert.rejects(db.exec("select review_save_experience('{}',array[]::uuid[])"),/owner access/);
await db.exec(`update review_student_hub_settings set inherit_features=false,show_music=true,updated_by='${ids.otherTeacher}' where student_id='${ids.other}'`);
await as('other');
assert.equal(await scalar("select review_my_hub_settings()->>'show_music'"),'true','Existing individual mode overrides global');
await db.exec(`update review_student_hub_settings set show_music=false where student_id='${ids.other}'`).then(()=>{},()=>{});
assert.equal(await scalar("select review_my_hub_settings()->>'show_music'"),'true','Learner cannot change teacher policy');
await as('teacher');
await db.exec(`select review_save_experience((select to_jsonb(c)||jsonb_build_object('features',c.features||'{"show_music":true}'::jsonb) from review_site_experience c where id),array[]::uuid[])`);
await as('student');
assert.equal(await scalar("select review_my_hub_settings()->>'show_music'"),'true','Global re-enable persists');
await as();
await assert.rejects(db.exec("select review_save_experience('{}',array[]::uuid[])"),/permission denied/);
await db.close();
console.log('Music policy: owner-only global save, inheritance, individual override and learner/anonymous restrictions passed.');
